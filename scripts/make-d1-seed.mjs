// Fallback loader: builds d1/seed.sql from website/snapshot/*.json.
// Only needed if you can't restore a full backup file through the Build Creator.
// Usage (from repo root): node scripts/make-d1-seed.mjs
// Then paste d1/seed.sql into the D1 console (after d1/schema.sql).
import fs from 'node:fs';

const SNAP = 'website/snapshot';
const read = k => JSON.parse(fs.readFileSync(`${SNAP}/${k}.json`, 'utf8'));
const sq = s => "'" + String(s).replace(/'/g, "''") + "'";   // SQLite string literal

const PUBLIC_DATASETS = ['gear', 'gear-logo-map', 'talents', 'weapon-classes'];
const builds = read('builds');

// Block comments only: the D1 console joins lines, so a "--" comment would swallow everything after it.
let out = `/* SHD FIELD TOOLKIT — INITIAL DATA FOR D1 (generated by scripts/make-d1-seed.mjs). Run AFTER d1/schema.sql. Existing rows are left alone (INSERT OR IGNORE). */
`;
for (const k of PUBLIC_DATASETS) {
  out += `INSERT OR IGNORE INTO datasets (key, data, published, updated_by) VALUES (${sq(k)}, ${sq(JSON.stringify(read(k)))}, 1, 'seed');\n`;
}
builds.forEach((b, i) => {
  out += `INSERT OR IGNORE INTO builds (id, category, status, sort_order, data, updated_by) VALUES (${sq(b.id)}, ${sq(b.cat)}, 'published', ${(i + 1) * 10}, ${sq(JSON.stringify(b))}, 'seed');\n`;
});
out += `SELECT (SELECT COUNT(*) FROM datasets) AS datasets, (SELECT COUNT(*) FROM builds) AS builds;\n`;

fs.mkdirSync('d1', { recursive: true });
fs.writeFileSync('d1/seed.sql', out);
console.log(`wrote d1/seed.sql (${(out.length / 1024).toFixed(0)} KB): ${PUBLIC_DATASETS.length} datasets, ${builds.length} builds`);
